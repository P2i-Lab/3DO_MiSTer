#!/usr/bin/env python3
"""Inputs of the NVRAM testbench.

    prepare.py CORE_DIR BUILD_DIR

- BUILD_DIR/save_load.svh: the save/load logic of CORE_DIR/3DO.sv, taken as is (from the
  "STATE SAVE/LOAD" section to the end of the P3DO_NVRAM_FMT instance, or to the
  sd_buff_din assignment in a 3DO.sv without that module), and the nvram_* connections
  of its ddram instance, turned into assignments to and from the tb_nvram_* signals.
- BUILD_DIR/img/NAME.{sd,nv,sav}.memh for each test save file: the file as Main_MiSTer
  sends it (16-bit words, byte 2k in bits 7:0), the NVRAM expected after loading it
  (16-bit words, byte 2k in bits 15:8) and the file expected after saving it back.
- BUILD_DIR/scenarios.svh: the list of test save files.

With MAIN=/path/to/Main_MiSTer, the blank save below is checked against save_blank in
Main_MiSTer's support/3do/3do.cpp.
"""
import os
import random
import re
import sys

NVRAM_SIZE = 32768

# Blank NVRAM written by Main_MiSTer for a new save (save_blank in support/3do/3do.cpp,
# first 256 bytes of sector 0, zeros elsewhere)
BLANK_HEAD = bytes.fromhex("".join((
    "01 5a 5a 5a 5a 5a 02 00 00 00 00 00 00 00 00 00",   # 0x00 label: type 1, sync, version 2
    "00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00",
    "00 00 00 00 00 00 00 00 4e 56 52 41 4d 00 00 00",   # 0x28 "NVRAM"
    "00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00",
    "00 00 00 00 00 00 00 00 ff ff ff ff 00 00 00 01",   # 0x48 unique id, block size
    "00 00 80 00 ff ff ff fe 00 00 00 00 00 00 00 01",   # 0x50 block count, root id, root block size
    "00 00 00 00 00 00 00 84 00 00 00 00 00 00 00 00",   # 0x64 root avatar 0x84
    "00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00",
    "00 00 00 00 85 5a 02 b6 00 00 00 98 00 00 00 98",   # 0x84 anchor block
    "00 00 00 14 00 00 00 14 7a a5 65 bd 00 00 00 84",   # 0x98 free block
    "00 00 00 84 00 00 7f 68 00 00 00 14 00 00 00 00",
) + ("00 " * 16,) * 5).replace(" ", ""))
assert len(BLANK_HEAD) == 256
BLANK = BLANK_HEAD + bytes(NVRAM_SIZE - 256)


def check_against_main(main_dir):
    src = open(os.path.join(main_dir, "support", "3do", "3do.cpp"), encoding="utf-8").read()
    m = re.search(r"save_blank\[\]\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        sys.exit("save_blank not found in Main_MiSTer support/3do/3do.cpp")
    main = bytes(int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", m.group(1)))
    if main != BLANK_HEAD:
        sys.exit("blank save differs from Main_MiSTer's save_blank")
    print("blank save matches Main_MiSTer save_blank (%d bytes)" % len(main))


def drop_block_initializers(block):
    """Verilator 5.0 rejects a variable declared with an initial value inside an always block
    and assigned with <= there ("reg old_load = 0;"). The initial values are dropped: Verilator
    starts all variables at 0, which is what they set."""
    out, in_decl = [], False
    for l in block:
        if re.search(r"\balways\b.*\bbegin\b", l):
            in_decl = True
        elif in_decl and re.match(r"\s*(reg|bit|logic)\b", l):
            l = re.sub(r"\s*=\s*[^,;]+", "", l)
        else:
            in_decl = False
        out.append(l)
    return out


def extract(core_dir):
    lines = open(os.path.join(core_dir, "3DO.sv"), encoding="utf-8", errors="replace").read().splitlines()
    start = next(i for i, l in enumerate(lines) if "STATE SAVE/LOAD" in l)
    end = None
    for i in range(start, len(lines)):
        if re.match(r"\s*P3DO_NVRAM_FMT\b", lines[i]):
            end = next(j for j in range(i, len(lines)) if re.match(r"\s*\);", lines[j]))
            break
    if end is None:
        end = next(i for i in range(start, len(lines)) if re.search(r"\bassign\s+sd_buff_din\b", lines[i]))
    block = drop_block_initializers(lines[start:end + 1])
    ports = {}
    for l in lines:
        m = re.match(r"\s*\.(nvram_(?:addr|din|wr|rd|dout|busy))\s*\((.*)\)\s*,?\s*(//.*)?$", l)
        if m:
            ports[m.group(1)] = m.group(2).strip()
    out = ["// Generated by prepare.py from %s: do not edit" % os.path.join(core_dir, "3DO.sv")]
    out += block
    out.append("")
    out.append("// nvram_* connections of the ddram instance")
    for p in ("nvram_addr", "nvram_din", "nvram_wr", "nvram_rd"):
        out.append("assign tb_%s = %s;" % (p, ports[p]))
    for p in ("nvram_dout", "nvram_busy"):
        out.append("assign %s = tb_%s;" % (ports[p], p))
    return "\n".join(out) + "\n"


def formatted(b):
    """Volume label: record type 1, five sync bytes 0x5A, structure version 2 (linked memory)."""
    return b[0] == 0x01 and b[1:6] == b"\x5a" * 5 and b[6] == 0x02


def words(b, nvram_order):
    if nvram_order:
        return ["%04x" % (b[2 * k] << 8 | b[2 * k + 1]) for k in range(len(b) // 2)]
    return ["%04x" % (b[2 * k] | b[2 * k + 1] << 8) for k in range(len(b) // 2)]


def images():
    rnd = random.Random(3)
    rand = lambda n: bytes(rnd.getrandbits(8) for _ in range(n))
    imgs = []
    # (name, contents, manual load from the OSD instead of a mount by Main_MiSTer)
    imgs.append(("main_blank", BLANK, False))
    imgs.append(("zero", bytes(NVRAM_SIZE), False))
    used = bytearray(BLANK)
    used[7] = 0x01                                   # label flags
    used[0xAC:512] = rand(512 - 0xAC)                # rest of sector 0
    used[512:] = rand(NVRAM_SIZE - 512)              # sectors 1-63
    imgs.append(("in_use", bytes(used), False))
    imgs.append(("ff", b"\xff" * NVRAM_SIZE, False))
    garbage = bytearray(rand(NVRAM_SIZE))
    garbage[0] = 0x00
    imgs.append(("garbage", bytes(garbage), True))
    bad_sync = bytearray(BLANK)
    bad_sync[5] = 0x5B
    bad_sync[512:] = rand(NVRAM_SIZE - 512)
    imgs.append(("bad_sync", bytes(bad_sync), False))
    version1 = bytearray(rand(NVRAM_SIZE))
    version1[0:7] = b"\x01" + b"\x5a" * 5 + b"\x01"
    imgs.append(("version1", bytes(version1), True))
    imgs.append(("zero_again", bytes(NVRAM_SIZE), True))
    return imgs


def main():
    core_dir, build = sys.argv[1], sys.argv[2]
    if os.environ.get("MAIN"):
        check_against_main(os.environ["MAIN"])
    os.makedirs(os.path.join(build, "img"), exist_ok=True)
    open(os.path.join(build, "save_load.svh"), "w").write(extract(core_dir))
    scen = []
    for name, b, manual in images():
        assert len(b) == NVRAM_SIZE
        eff = b if formatted(b) else BLANK
        for ext, data in (("sd", words(b, False)), ("nv", words(eff, True)), ("sav", words(eff, False))):
            open(os.path.join(build, "img", "%s.%s.memh" % (name, ext)), "w").write("\n".join(data) + "\n")
        scen.append('scenario("%s", %d, %d);' % (name, int(manual), int(formatted(b))))
    open(os.path.join(build, "scenarios.svh"), "w").write("\n".join(scen) + "\n")


if __name__ == "__main__":
    main()
